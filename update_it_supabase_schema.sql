-- ---------------------------------------------------------------------
-- 11. ROW LEVEL SECURITY
--     Django connects with the database owner role (postgres), which
--     bypasses RLS, so the app keeps working. Enabling RLS with NO
--     policies blocks the public anon/authenticated API keys from
--     reading or writing any of these tables via Supabase's REST API.
-- ---------------------------------------------------------------------

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'classes','batches','faculty','subjects','teacher_subjects','class_schedule',
    'students','admission_info','admission_inquiries','admission_applications',
    'attendance','faculty_attendance','exams','exam_results',
    'student_payments','student_payment_receipts','teacher_salary','expenses',
    'notices','achievements','gallery','gallery_sections','gallery_subsections',
    'contact_messages','users'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

