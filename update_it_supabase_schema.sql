-- ---------------------------------------------------------------------
-- 1. ACADEMIC STRUCTURE
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.classes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name     VARCHAR(100) NOT NULL,
    academic_year  INTEGER      NOT NULL,
    CONSTRAINT classes_name_year_uniq UNIQUE (class_name, academic_year)
);

CREATE TABLE IF NOT EXISTS public.batches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id    BIGINT       NOT NULL REFERENCES public.classes(id),
    batch_name  VARCHAR(100) NOT NULL,
    room        VARCHAR(50),
    start_time  TIME,
    end_time    TIME,
    CONSTRAINT batches_class_batch_uniq UNIQUE (class_id, batch_name)
);

CREATE TABLE IF NOT EXISTS public.faculty (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    photo_url     TEXT,
    designation   VARCHAR(100),
    phone         VARCHAR(20),
    email         VARCHAR(150),
    joining_date  DATE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.subjects (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id      BIGINT       NOT NULL REFERENCES public.classes(id),
    subject_name  VARCHAR(100) NOT NULL,
    subject_code  VARCHAR(30)  UNIQUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT subjects_name_class_uniq UNIQUE (subject_name, class_id)
);

-- Composite primary key (Django 5.2 CompositePrimaryKey)
CREATE TABLE IF NOT EXISTS public.teacher_subjects (
    teacher_id  BIGINT NOT NULL REFERENCES public.faculty(id),
    subject_id  BIGINT NOT NULL REFERENCES public.subjects(id),
    PRIMARY KEY (teacher_id, subject_id)
);

CREATE TABLE IF NOT EXISTS public.class_schedule (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id     BIGINT      NOT NULL REFERENCES public.classes(id),
    batch_id     BIGINT      NOT NULL REFERENCES public.batches(id),
    teacher_id   BIGINT      NOT NULL REFERENCES public.faculty(id),
    subject_id   BIGINT      NOT NULL REFERENCES public.subjects(id),
    day_of_week  VARCHAR(20) NOT NULL,
    start_time   TIME        NOT NULL,
    end_time     TIME        NOT NULL,
    room         VARCHAR(50),
    status       VARCHAR(20) NOT NULL DEFAULT 'Active'
                 CHECK (status IN ('Active','Cancelled','Rescheduled')),
    notes        TEXT
);

-- ---------------------------------------------------------------------
-- 2. STUDENTS
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.students (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_code     VARCHAR(30)  NOT NULL UNIQUE,
    class_id         BIGINT       NOT NULL REFERENCES public.classes(id),
    batch_id         BIGINT       REFERENCES public.batches(id),
    "group"          VARCHAR(100),
    full_name        VARCHAR(150) NOT NULL,
    photo_url        TEXT,
    gender           VARCHAR(20),
    date_of_birth    DATE,
    institution_name VARCHAR(200),
    blood_group      VARCHAR(5),
    reference        VARCHAR(200),
    student_phone    VARCHAR(20),
    father_name      VARCHAR(150),
    father_phone     VARCHAR(20),
    mother_name      VARCHAR(150),
    mother_phone     VARCHAR(20),
    address          TEXT,
    admission_date   DATE,
    status           VARCHAR(20)  NOT NULL DEFAULT 'Active'
                     CHECK (status IN ('Active','Inactive','Completed','Left'))
);

-- ---------------------------------------------------------------------
-- 3. ADMISSIONS
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.admission_info (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(200) NOT NULL,
    description    TEXT,
    image_url      TEXT,
    admission_fee  NUMERIC(10,2) CHECK (admission_fee >= 0),
    monthly_fee    NUMERIC(10,2) CHECK (monthly_fee   >= 0),
    duration       VARCHAR(100),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.admission_inquiries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name    VARCHAR(150) NOT NULL,
    student_phone   VARCHAR(20)  NOT NULL,
    guardian_name   VARCHAR(150),
    guardian_phone  VARCHAR(20),
    class_id        BIGINT REFERENCES public.classes(id) ON DELETE SET NULL,
    message         TEXT,
    status          VARCHAR(20) NOT NULL DEFAULT 'New'
                    CHECK (status IN ('New','Contacted','Admitted','Rejected')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.admission_applications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id         BIGINT REFERENCES public.admission_info(id) ON DELETE SET NULL,
    course_title      VARCHAR(200),
    student_name      VARCHAR(150) NOT NULL,
    date_of_birth     DATE         NOT NULL,
    gender            VARCHAR(20),
    student_phone     VARCHAR(20),
    institution_name  VARCHAR(200),
    blood_group       VARCHAR(5),
    address           TEXT,
    guardian_name     VARCHAR(150) NOT NULL,
    guardian_relation VARCHAR(20)  NOT NULL DEFAULT 'Father',
    guardian_phone    VARCHAR(20)  NOT NULL,
    preferred_batch   VARCHAR(150),
    reference         VARCHAR(200),
    message           TEXT,
    status            VARCHAR(20)  NOT NULL DEFAULT 'Pending'
                      CHECK (status IN ('Pending','Contacted','Verified','Admitted','Rejected')),
    staff_notes       TEXT,
    student_id        BIGINT REFERENCES public.students(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 4. ATTENDANCE
-- ---------------------------------------------------------------------

-- NOTE: matches models.py — one record per student per day (system-wide).
CREATE TABLE IF NOT EXISTS public.attendance (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id       BIGINT      NOT NULL REFERENCES public.students(id),
    batch_id         BIGINT      NOT NULL REFERENCES public.batches(id),
    attendance_date  DATE        NOT NULL,
    status           VARCHAR(20) NOT NULL
                     CHECK (status IN ('Present','Absent','Late')),
    remarks          TEXT,
    CONSTRAINT attendance_student_date_uniq UNIQUE (student_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS public.faculty_attendance (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id       BIGINT      NOT NULL REFERENCES public.faculty(id),
    attendance_date  DATE        NOT NULL,
    status           VARCHAR(20) NOT NULL
                     CHECK (status IN ('Present','Absent','Late')),
    classes_taken    INTEGER     NOT NULL DEFAULT 0 CHECK (classes_taken >= 0),
    remarks          TEXT,
    CONSTRAINT faculty_attendance_teacher_date_uniq UNIQUE (teacher_id, attendance_date)
);

-- ---------------------------------------------------------------------
-- 5. EXAMS & RESULTS
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.exams (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id    BIGINT       NOT NULL REFERENCES public.classes(id),
    exam_name   VARCHAR(100) NOT NULL,
    exam_date   DATE         NOT NULL,
    full_marks  NUMERIC(6,2) NOT NULL DEFAULT 100 CHECK (full_marks >= 1)
);

CREATE TABLE IF NOT EXISTS public.exam_results (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id     BIGINT       NOT NULL REFERENCES public.exams(id),
    student_id  BIGINT       NOT NULL REFERENCES public.students(id),
    subject_id  BIGINT       NOT NULL REFERENCES public.subjects(id),
    marks       NUMERIC(5,2) NOT NULL CHECK (marks >= 0),
    grade       VARCHAR(10),
    CONSTRAINT exam_results_exam_student_subject_uniq UNIQUE (exam_id, student_id, subject_id)
);

-- ---------------------------------------------------------------------
-- 6. STUDENT PAYMENTS
-- ---------------------------------------------------------------------

-- Legacy one-payment-per-row table (kept for history)
CREATE TABLE IF NOT EXISTS public.student_payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT       NOT NULL REFERENCES public.students(id),
    payment_type   VARCHAR(30)  NOT NULL
                   CHECK (payment_type IN ('Admission Fee','Monthly Fee','Exam Fee','Registration Fee','Other')),
    amount         NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    payment_date   DATE         NOT NULL,
    payment_month  DATE,
    remarks        TEXT
);

-- Current multi-item receipt table. `items` is a JSON list of line items:
-- {"payment_type","payment_month","label","amount","discount","net"}
CREATE TABLE IF NOT EXISTS public.student_payment_receipts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT       NOT NULL REFERENCES public.students(id),
    receipt_number  VARCHAR(50)  UNIQUE,
    payment_date    DATE         NOT NULL,
    payment_method  VARCHAR(20)  NOT NULL DEFAULT 'Cash'
                    CHECK (payment_method IN ('Cash','Bank','Bkash','Nagad')),
    transaction_id  VARCHAR(100),
    items           JSONB        NOT NULL DEFAULT '[]'::jsonb,
    total_amount    NUMERIC(10,2) NOT NULL DEFAULT 0,
    total_discount  NUMERIC(10,2) NOT NULL DEFAULT 0,
    remarks         TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 7. TEACHER SALARY & EXPENSES
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.teacher_salary (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id            BIGINT       NOT NULL REFERENCES public.faculty(id),
    salary_month          DATE         NOT NULL,
    amount                NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    receipt_number        VARCHAR(50)  UNIQUE,
    gross_salary          NUMERIC(10,2) NOT NULL DEFAULT 0,
    bonus                 NUMERIC(10,2) NOT NULL DEFAULT 0,
    classes_taken         INTEGER      NOT NULL DEFAULT 0 CHECK (classes_taken >= 0),
    rate_per_class        NUMERIC(10,2) NOT NULL DEFAULT 0,
    class_based_pay       NUMERIC(10,2) NOT NULL DEFAULT 0,
    deduction             NUMERIC(10,2) NOT NULL DEFAULT 0,
    present_days          INTEGER      NOT NULL DEFAULT 0 CHECK (present_days >= 0),
    absent_days           INTEGER      NOT NULL DEFAULT 0 CHECK (absent_days  >= 0),
    late_days             INTEGER      NOT NULL DEFAULT 0 CHECK (late_days    >= 0),
    attendance_deduction  NUMERIC(10,2) NOT NULL DEFAULT 0,
    net_salary            NUMERIC(10,2) NOT NULL DEFAULT 0,
    paid_amount           NUMERIC(10,2) NOT NULL DEFAULT 0,
    due_amount            NUMERIC(10,2) NOT NULL DEFAULT 0,
    payment_method        VARCHAR(20)  NOT NULL DEFAULT 'Cash'
                          CHECK (payment_method IN ('Cash','Bank','Bkash','Nagad')),
    transaction_id        VARCHAR(100),
    payment_date          DATE,
    status                VARCHAR(20)  NOT NULL DEFAULT 'Pending'
                          CHECK (status IN ('Pending','Partial','Paid')),
    remarks               TEXT,
    CONSTRAINT teacher_salary_teacher_month_uniq UNIQUE (teacher_id, salary_month)
);

CREATE TABLE IF NOT EXISTS public.expenses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    category        VARCHAR(30)  NOT NULL DEFAULT 'Other'
                    CHECK (category IN ('Rent','Utilities','Supplies','Maintenance',
                                        'Marketing','Equipment','Events','Other')),
    amount          NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    expense_date    DATE         NOT NULL,
    payment_method  VARCHAR(20)  NOT NULL DEFAULT 'Cash'
                    CHECK (payment_method IN ('Cash','Bank','Bkash','Nagad')),
    remarks         TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

